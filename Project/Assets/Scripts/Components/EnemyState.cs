namespace Project06.Components
{
    public enum EnemyState
    {
        // 제자리에 서서 대기 시간이 끝나기를 기다린다. 끝나면 쫓을 쉘터가 있으면 Chase가 되고, 없으면 계속 서 있는다. 플레이어가 감지 반지름에 들어오면 바로 Chase가 된다.
        Idle,
        // 목표(플레이어 또는 쉘터)를 NavMesh 경로로 쫓는다. 쫓던 플레이어가 해제 반지름 밖으로 나가면 놓친 뒤 대기 시간만큼 Idle이 되고, 쫓던 쉘터가 파괴되면 Idle이 된다.
        Chase,
        // 제자리에 서서 근접 또는 원거리 공격을 하고 있다. 목표가 사거리를 벗어나도 끝까지 하고, 끝나면 Chase가 된다.
        Attack,
        // 피격 경직 중이다. 제자리에 서 있고, 경직이 끝나면 Chase가 된다. 경직 중에 다시 경직에 걸리면 처음부터 다시 센다.
        HitStun,
        // 체력이 0 이하가 되어 사망 애니메이션을 보여 주는 중이다. 움직이지 않고 맞지 않으며, 사망 시간이 끝나면 소멸한다.
        Dead,
    }
}
